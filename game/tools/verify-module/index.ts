/**
 * The module agent's verification gate (ARCHITECTURE.md §16):
 *
 *   npm run verify:module -- <moduleId>        (also: npm run tool -- verify-module <moduleId>)
 *
 * Checks ONE module in isolation, so other agents' half-finished modules cannot fail it:
 *   1. typecheck of a generated program containing only the kernel (src/sim/core, src/sim/save,
 *      src/sim/testing.ts), src/content and the module's folder (with its tests);
 *   2. the module's own tests (vitest run <folder>);
 *   3. the architecture boundary rules scoped to the module's folder.
 * The full gate (`npm run typecheck && npm test && npm run build && npm run sim -- --days 365`)
 * belongs to the integrator.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MODULE_AREAS } from '../../src/content/areas';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const SUB_SIMS = ['battle', 'duel', 'seabattle'];

function folderFor(id: string): string {
  return SUB_SIMS.includes(id) ? join('src', 'sim', id) : join('src', 'sim', 'modules', id);
}

function run(label: string, command: string, args: string[], env: NodeJS.ProcessEnv = {}): boolean {
  console.log(`\n▶ ${label}`);
  // One command string (no args array) so Windows' shell resolution of npx works without DEP0190.
  const line = [command, ...args.map((a) => (/[\s"]/.test(a) ? JSON.stringify(a) : a))].join(' ');
  const r = spawnSync(line, { cwd: ROOT, stdio: 'inherit', shell: true, env: { ...process.env, ...env } });
  const ok = r.status === 0;
  console.log(ok ? `✔ ${label}` : `✘ ${label} (exit ${String(r.status)})`);
  return ok;
}

function main(): void {
  const id = process.argv[2];
  if (!id || !(MODULE_AREAS as readonly string[]).includes(id)) {
    console.error(`usage: npm run verify:module -- <moduleId>\nmodule ids: ${MODULE_AREAS.join(', ')}`);
    process.exitCode = 1;
    return;
  }
  const folder = folderFor(id).replaceAll('\\', '/');
  if (!existsSync(join(ROOT, folder))) {
    console.error(`module folder ${folder} does not exist`);
    process.exitCode = 1;
    return;
  }
  const cacheDir = join(ROOT, 'node_modules', '.cache', 'bardia');
  mkdirSync(cacheDir, { recursive: true });
  const rel = (p: string) => relative(cacheDir, join(ROOT, p)).replaceAll('\\', '/');
  const tsconfig = {
    '//': `Generated by tools/verify-module for '${id}'. Do not edit.`,
    extends: rel('tsconfig.base.json'),
    include: [rel('src/sim/core'), rel('src/sim/save'), rel('src/sim/testing.ts'), rel('src/content'), rel(folder)],
    exclude: [rel('src/sim/core/**/*.test.ts'), rel('src/sim/save/**/*.test.ts'), rel('src/content/**/*.test.ts')],
  };
  const tsconfigPath = join(cacheDir, `tsconfig.module.${id}.json`);
  writeFileSync(tsconfigPath, `${JSON.stringify(tsconfig, null, 2)}\n`);

  const results = [
    run(`typecheck ${id} (kernel + content + ${folder})`, 'npx', ['tsc', '--noEmit', '-p', relative(ROOT, tsconfigPath)]),
    run(`tests in ${folder}`, 'npx', ['vitest', 'run', folder, '--passWithNoTests']),
    run(`boundary rules for ${folder}`, 'npx', ['vitest', 'run', 'src/sim/boundary.test.ts'], { BARDIA_BOUNDARY_SCOPE: folder }),
  ];
  const ok = results.every(Boolean);
  console.log(ok ? `\nmodule '${id}' verified.` : `\nmodule '${id}' FAILED verification.`);
  if (!ok) process.exitCode = 1;
}

main();
